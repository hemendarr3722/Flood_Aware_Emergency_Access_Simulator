"""
scripts/fix_supabase_schema_and_scenarios.py
Update route_to_destinations and align scenario IDs on Supabase.
"""
import os
import psycopg

db_url = os.environ.get("DATABASE_URL")
if not db_url:
    raise RuntimeError("DATABASE_URL must be set.")

conn = psycopg.connect(db_url)
cur = conn.cursor()

# 1. Update route_to_destinations function
cur.execute("""
create or replace function gis.route_to_destinations(
  p_start bigint,
  p_targets bigint[],
  p_scenario bigint default null
)
returns table(
  seq integer,
  path_seq integer,
  start_vid bigint,
  end_vid bigint,
  node bigint,
  edge bigint,
  cost double precision,
  agg_cost double precision
)
language plpgsql
security invoker
set search_path = extensions, public, gis
as $fn$
begin
  return query
  select d.seq, d.path_seq, p_start as start_vid, d.end_vid, d.node, d.edge, d.cost, d.agg_cost
  from pgr_dijkstra(
    format(
      $q$select e.id, e.source, e.target,
        case when exists (
          select 1 from gis.scenario_edge_impacts i
          where i.edge_id = e.id and i.scenario_id = %s and i.is_closed
        ) then -1.0 else e.cost_s end as cost,
        case when exists (
          select 1 from gis.scenario_edge_impacts i
          where i.edge_id = e.id and i.scenario_id = %s and i.is_closed
        ) then -1.0 else e.reverse_cost_s end as reverse_cost
        from gis.road_edges e$q$,
      coalesce(p_scenario, -1),
      coalesce(p_scenario, -1)
    ),
    p_start,
    p_targets,
    directed := true
  ) d;
end;
$fn$;
revoke execute on function gis.route_to_destinations(bigint, bigint[], bigint) from public;
""")
print("Updated gis.route_to_destinations successfully.")

# 2. Check and re-align scenario IDs: Scenario 1 = Baseline, Scenario 2 = FEMA 100-Year SFHA
cur.execute("alter table gis.flood_scenarios alter column id set generated by default;")
cur.execute("set session_replication_role = replica;")

# Check current IDs
cur.execute("select id, name, scenario_kind from gis.flood_scenarios order by id;")
rows = cur.fetchall()
print("Current scenarios:", rows)

# Find baseline and flood
baseline_id = None
flood_id = None
for sid, sname, skind in rows:
    if skind == "baseline":
        baseline_id = sid
    elif skind == "hazard_polygon":
        flood_id = sid

if baseline_id is not None and flood_id is not None:
    # Update edge impacts
    cur.execute("update gis.scenario_edge_impacts set scenario_id = 999 where scenario_id = %s;", (flood_id,))
    cur.execute("update gis.scenario_edge_impacts set scenario_id = 2 where scenario_id = 999;")
    
    # Update accessibility
    cur.execute("update gis.scenario_accessibility set scenario_id = 998 where scenario_id = %s;", (baseline_id,))
    cur.execute("update gis.scenario_accessibility set scenario_id = 999 where scenario_id = %s;", (flood_id,))
    cur.execute("update gis.scenario_accessibility set scenario_id = 1 where scenario_id = 998;")
    cur.execute("update gis.scenario_accessibility set scenario_id = 2 where scenario_id = 999;")

    # Update flood_scenarios
    cur.execute("update gis.flood_scenarios set id = 998 where id = %s;", (baseline_id,))
    cur.execute("update gis.flood_scenarios set id = 999 where id = %s;", (flood_id,))
    cur.execute("update gis.flood_scenarios set id = 1 where id = 998;")
    cur.execute("update gis.flood_scenarios set id = 2 where id = 999;")

    cur.execute("select setval(pg_get_serial_sequence('gis.flood_scenarios', 'id'), 2);")
    print("Re-aligned scenario IDs to 1 (baseline) and 2 (hazard_polygon).")

cur.execute("set session_replication_role = DEFAULT;")
cur.execute("alter table gis.flood_scenarios alter column id set generated always;")
conn.commit()

# Test routing
cur.execute("select * from gis.route_nearest_facility(151461824, 'hospital', 1, 1);")
hosp_route = cur.fetchone()
print("Nearest hospital route:", hosp_route)

cur.execute("select * from gis.route_nearest_facility(151461824, 'fire_station', 1, 1);")
fire_route = cur.fetchone()
print("Nearest fire station route:", fire_route)

conn.close()
print("All adjustments complete.")
